function met = f_case_metrics(cse, des, cfg)
% ==================================================================
% met = f_case_metrics(cse, des, cfg)
%
% Metrics of Table 2 / Table 3:
%   finite-horizon cost J = state part + rate part, angle RMSE (full horizon and
%   last cfg.tailWindow s), settling time (|theta - theta*| <= cfg.settlingBand),
%   final errors, command ranges, HJ use and the fallback statistics.
% Also checks the guarantees of Proposition 1(c): 0 < sigma(u) < 1 and
% |d sigma(u)/dt| <= |nu|.
% ==================================================================
t = cse.t; z = cse.z; nu = cse.nu;
q = z - des.zStar'; e = q(:,1); uRaw = z(:,5); u = cse.u; duration = max(t(end) - t(1), eps);
tail = t >= max(t(1), t(end) - cfg.tailWindow); tt = t(tail); te = e(tail);
tailDuration = max(tt(end) - tt(1), eps); dt = diff(t);
mid = (cfg.uMin + cfg.uMax)/2;
nearest = min(max(mid, min(uRaw(1:end-1), uRaw(2:end))), max(uRaw(1:end-1), uRaw(2:end)));
peakAppliedRate = max(abs(nu).*des.prob.saturationDerivative(nearest));
reasons = cse.fallbackReason;
met = struct('thetaRMSE', sqrt(trapz(t, e.^2)/duration), ...
    'tailThetaRMSE', sqrt(trapz(tt, te.^2)/tailDuration), 'peakThetaError', max(abs(e)), ...
    'tailPeakThetaError', max(abs(te)), 'finalThetaError', e(end), ...
    'finalStateErrorNorm', norm(q(end,:)), 'finalPhysicalStateErrorNorm', norm(q(end,1:4)), ...
    'finalScaledStateErrorNorm', norm(q(end,:)./des.scale'), ...
    'finalPressureError', q(end,3), 'finalHysteresisError', q(end,4), ...
    'finalAppliedCommandError', u(end) - des.uAppliedStar, 'finalRawCommandError', q(end,5), ...
    'settlingTime', f_settling_time(t, e, cfg.settlingBand), ...
    'stateCost', cse.stateCostIntegral(end), 'rateCost', cse.rateCostIntegral(end), ...
    'finiteHorizonCost', cse.stateCostIntegral(end) + cse.rateCostIntegral(end), ...
    'angleStateCost', des.Qphysical(1,1)*trapz(t, e.^2), ...
    'controlDeviationRMS', sqrt(trapz(t, (u - des.uAppliedStar).^2)/duration), ...
    'rateRMS', sqrt(sum(dt.*nu.^2)/duration), 'controlMin', min(u), 'controlMax', max(u), ...
    'rawCommandMin', min(uRaw), 'rawCommandMax', max(uRaw), ...
    'maximumRate', max(abs(nu)), 'maximumAppliedRate', peakAppliedRate, ...
    'peakDisturbanceTorque', max(abs(cse.disturbanceTorque)), ...
    'hjUseFraction', mean(cse.hjUsed), 'hjUsedIntervals', sum(cse.hjUsed), ...
    'fallbackDomain', sum(reasons == 1), 'fallbackValue', sum(reasons == 2), ...
    'fallbackResidual', sum(reasons == 3), 'fallbackGuard', sum(reasons == 4), ...
    'rateBoundActiveHJ', sum(cse.hjUsed & abs(nu) >= cfg.uRateMax - 1e-9), ...
    'saturationCompressionFraction', mean(des.prob.saturationDerivative(uRaw) < 0.5));
assert(all(u >= cfg.uMin - 1e-9 & u <= cfg.uMax + 1e-9), 'Applied-command saturation bound violated.');
assert(all(abs(nu) <= cfg.uRateMax + 1e-8), 'Rate-input bound violated.');
assert(max(abs(diff(uRaw)./dt - nu)) < 1e-7, 'RAW command integration and held rate disagree.');
assert(peakAppliedRate <= cfg.uRateMax + 1e-8, 'Applied command rate exceeds its guaranteed bound.');
if ~strcmp(cse.status,'completed')
    met.thetaRMSE = inf; met.tailThetaRMSE = inf; met.finiteHorizonCost = inf; met.settlingTime = inf;
end
end
