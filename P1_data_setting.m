	'stiffness of F', min(rlptF)/max(rlptF), 'be careful if >10'; ...
	'det of Trs (eig vectors of F)', det(Trs), 'be careful if this is 0'; ...
	'Riccati residual', des.riccatiResidual, 'paper: 2.1e-13'; ...
	'block-diagonalisation residual', des.diagonalizationResidual, 'paper: 4.8e-13'; ...
	'manifold horizon T_m [s]', des.horizon, 'paper: 672.5'; ...
	'K5*S^-1', des.Kphysical, 'paper: [-1.674 11.236 17.590 26.795 20.883]'; ...
	'generated files vs runtime problem', generatedFileCheck, 'relative; ~1e-13 for nominal parameters'};
