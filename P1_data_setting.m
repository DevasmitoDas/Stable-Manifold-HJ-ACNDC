% ==================================================================
% P1: 共通パラメータの設定 / data setting and local design
%
% inputData/<problem> 内のデータを読み込む / reads the problem folder:
%   - systemData.m   flags, par, cfg, prob (symbolic or analytic), A, B, Q, R ...
%   - symbSetting.m  symbolic plant, pre-Hamiltonian, nu*, Hbar, canonical field
%   - Decide_xi.m    seeds (used in P3)
% 対角行列と対角化行列を求める / local design and block diagonalisation
% (paper Sec. 3.2):
%   P5 : A5'P5 + P5A5 - P5B5 Rnu^{-1} B5'P5 + Qy = 0,   V(y) = y'P5y + O(|y|^3)
%   F  = A5 - D*Gamma, Gamma = 2*P5, D = B5B5'/(2Rnu)
%   L  : F*L + L*F' = D,  Diagonalize = T = [I L; Gamma Gamma*L+I]
% ==================================================================

if ~exist('rootFolder','var'), rootFolder = pwd; end

systemData    % 状態方程式の各行列の定義 / problem data

des = f_design(prob, cfg);      % see f_design.m

% === reference-toolbox names ===
% Toolbox convention p = P*x (V = 1/2 x'Px):  P = Gamma = 2*P5 = care(A,B,2Q,2R)
P5   = des.P;                   % paper: V(y) = y'*P5*y + O(|y|^3)
P    = des.Gamma;               % costate gain mu ~ P*y
K5   = des.K;                   % LQR rate gain in scaled coordinates
Rbar = des.D;                   % B*(2R)^(-1)*B'
F    = des.F;
Ft   = F';
L    = des.L;
Diagonalize = des.T;
Diag_inv    = des.Tinv;
Ham  = des.canonicalLinear;     % [A -Rbar; -2Q -A']

fprintf('\nProblem route : %s  (%s)\n', prob.route, prob.status)
fprintf('z* = [%g %g %g %g %g] (fifth state RAW u), sigma(u*) = %g\n', des.zStar, des.uAppliedStar)
fprintf('Diagonalization check : ||Diagonalize^(-1)*Ham*Diagonalize - diag(F,-F'')|| = %.3e\n', ...
	des.diagonalizationResidual)
fprintf('Riccati residual = %.3e,  manifold horizon T_m = %.4g s\n', des.riccatiResidual, des.horizon)
fprintf('Eigenvalues of F (closed-loop poles):\n'); disp(des.poles)
fprintf('Physical augmented LQR rate gain K5*S^-1:\n'); disp(des.Kphysical)

% === 各種行列表示 / real eigen-directions of F ===
% Trs consists of real eigenvectors v1,...,vn with the last column belonging to
% the eigenvalue closest to the imaginary axis (weakest damping).
try
	[eigF_blk,Trs] = ordblk(F,'real');
	Trs = Trs*rot90(eye(dim));
catch
	[Trs,~] = eig(F); Trs = real(Trs);
end

% === mathematical self-checks (Proposition 1, kernels, gradients) ===
checks = struct();
if cfg.selfCheckFlag == 1
	checks = f_self_checks(par, des, cfg);
end

% === consistency with the committed generated files (nominal parameters) ===
% f.m, g.m, HamF.m, HamG.m in the problem folder were generated by the Symbolic
% Math Toolbox for lambda_h = 0.02, Rnu = 0.02 (reference _sym convention).
generatedFileCheck = nan;
if exist('HamF','file') == 2 && exist('HamG','file') == 2 && exist('f','file') == 2
	Ychk = 0.3*(2*f_halton(40,[2 3 5 7 11],211) - 1);
	Mchk = 0.3*(2*f_halton(40,[13 17 19 23 29],311) - 1);
	ref_f = zeros(dim,40); ref_F = zeros(dim,40); ref_G = zeros(dim,40);
	try
		for i_chk = 1:40   % the generated files accept one column at a time
			ref_f(:,i_chk) = feval('f', Ychk(:,i_chk));
			ref_F(:,i_chk) = feval('HamF', Ychk(:,i_chk), Mchk(:,i_chk));
			ref_G(:,i_chk) = feval('HamG', Ychk(:,i_chk), Mchk(:,i_chk));
		end
		generatedFileCheck = max([norm(ref_f - prob.f(Ychk),'fro')/norm(ref_f,'fro'), ...
			norm(ref_F - prob.HamF(Ychk,Mchk),'fro')/max(norm(ref_F,'fro'),eps), ...
			norm(ref_G - prob.HamG(Ychk,Mchk),'fro')/max(norm(ref_G,'fro'),eps)]);
	catch
		generatedFileCheck = nan;
	end
	clear Ychk Mchk ref_f ref_F ref_G i_chk
end

% === optional LMI certificate of the Riccati solution (LMI/) ===
if cfg.lmiCheckFlag == 1
	addpath(fullfile(rootFolder,'LMI'))
	LMI_riccati_check
end

